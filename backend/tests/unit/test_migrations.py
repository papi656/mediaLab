"""D7: the schema ships as migrations, and the shipped schema is the models.

Three failure modes, one test each:

* a blank database that does not reach a working schema (the VPS first-boot path);
* models edited without a migration (the drift that `create_all` used to hide);
* a container that starts against a schema it does not know about (a skipped or
  failed pre-deployment step), which must be a startup error, not a runtime one.
"""

from __future__ import annotations

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import inspect

from app.config import Settings
from app.db import alembic_config, init_db, make_engine, require_at_head
from app.main import create_app


def _engine(tmp_path):
    settings = Settings(_env_file=None, provider="fake", data_dir=tmp_path / "data")
    settings.prepare_dirs()
    return settings, make_engine(settings.database_url)


def _head() -> str:
    return ScriptDirectory.from_config(alembic_config()).get_current_head()


def test_a_blank_database_reaches_head(tmp_path):
    """First boot on an empty /data: no stamp, no create_all, just `upgrade head`."""
    _settings, engine = _engine(tmp_path)

    init_db(engine)

    assert set(inspect(engine).get_table_names()) >= {"media_jobs", "assets", "spend_ledger"}
    require_at_head(engine)  # raises if the revision does not match head


def test_init_db_is_idempotent(tmp_path):
    """A redeploy runs the same command again; it must be a no-op, not an error."""
    _settings, engine = _engine(tmp_path)

    init_db(engine)
    init_db(engine)

    require_at_head(engine)


def test_models_and_migrations_do_not_drift(tmp_path):
    """Any model change without a revision fails here, not at the next deploy.

    This is the check `create_all` could never give: it silently created whatever the
    models said, so a missing migration was invisible until an existing database
    disagreed with the code.
    """
    _settings, engine = _engine(tmp_path)
    init_db(engine)

    config = alembic_config()
    with engine.connect() as connection:
        config.attributes["connection"] = connection
        command.check(config)  # raises AutogenerateDiffsDetected on drift


def test_a_stale_schema_refuses_to_boot(tmp_path):
    """Production shape: migrations are the pre-deploy step, so prove they ran."""
    settings, engine = _engine(tmp_path)
    assert settings.run_migrations_on_start is True

    with pytest.raises(RuntimeError) as caught:
        require_at_head(engine)  # nothing migrated yet
    message = str(caught.value)
    assert "alembic upgrade head" in message
    assert "head=" + _head() in message


def test_the_app_refuses_a_stale_schema_when_migrating_is_delegated(tmp_path):
    """`RUN_MIGRATIONS_ON_START=false` plus a skipped pre-deploy is a dead container."""
    settings = Settings(
        _env_file=None,
        provider="fake",
        data_dir=tmp_path / "data",
        run_migrations_on_start=False,
        admin_password="medialab",
        session_secret="test-secret-not-for-production",
    )

    with pytest.raises(RuntimeError):
        create_app(settings)


def test_the_app_migrates_itself_in_the_default_shape(tmp_path):
    settings = Settings(
        _env_file=None,
        provider="fake",
        data_dir=tmp_path / "data",
        admin_password="medialab",
        session_secret="test-secret-not-for-production",
    )

    create_app(settings)

    engine = make_engine(settings.database_url)
    require_at_head(engine)
